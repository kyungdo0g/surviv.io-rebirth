function statTables(): string {
    const out: string[] = [];
    out.push("# Gun tier stats (generated)");
    out.push("");
    out.push(
        "Generated by `tools/research/gun-tiers/report.ts` from `compute.ts` (method: [gun-tiers.md](gun-tiers.md)). Final defs: " +
            '`@rebirth/defs` `getDefOfType("gun", id)` with the rebirth layer applied. CSV twin: ' +
            "[gun-tiers-stats.csv](gun-tiers-stats.csv).",
    );
    out.push("");
    out.push("Columns:");
    out.push("");
    out.push("- **dmg**: bullet damage x pellets, + explosion (e) + shrapnel pieces x damage (s).");
    out.push("- **RPM**: average rate (bursts and pumps included). **mag**: magazine (extended).");
    out.push("- **reload**: seconds (full magazine), or seconds per shell batch (full reload).");
    out.push(
        "- **burst / sust. DPS**: damage per second at the cyclic rate / including the reload (a charge gun: per pickup).",
    );
    out.push("- **spread**: standing / moving (degrees). **speed**: bullet or projectile u/s.");
    out.push(
        "- **TTK avg**: expected seconds from the first shot at average aim (3.5°), mean over the class band, armour none / 1 / 2.",
    );
    out.push("- **exp A1**: expert aim (1.6°) at level 1. **perf A1**: every bullet hits (15 % headshots).");
    out.push(
        "- **F**: forgiveness, expert / beginner band TTK at level 1, fixed aim error. **mob**: speed held / firing (u/s).",
    );
    out.push("- **tier**: current → proposed (`=` unchanged).");
    for (const cls of CLASS_ORDER) {
        const ids = sortRows(M.rows.filter((r: Any) => r.cls === cls).map((r: Any) => r.id));
        if (!ids.length) continue;
        const band = row.get(ids[0]).band;
        out.push("");
        out.push(`## ${cls} (band ${band[0]}-${band[band.length - 1]} u)`);
        out.push("");
        out.push(
            "| gun | dmg | RPM | mag | reload | burst DPS | sust. DPS | spread | speed | TTK avg A0 / A1 / A2 | exp A1 | perf A1 | F | mob | tier |",
        );
        out.push("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|");
        for (const id of ids) {
            const r = row.get(id);
            const t = tier.get(id);
            const cur = t.current ?? "-";
            out.push(
                `| ${disp(id)} \`${id}\` | ${dmgStr(r)} | ${f0(r.rpm)} | ${r.mag}${r.magExt !== r.mag ? ` (${r.magExt})` : ""} | ${reloadStr(r)} | ${f0(r.burstDps)} | ${f0(r.sustainedDps)} | ${r.shotSpread} / ${r.moveSpread} | ${f0(r.bulletSpeed)} | ${ttk3(r.bandTtk.average)} | ${f(r.bandTtk.expert.a1)} | ${f(r.perfect.a1)} | ${f(r.F)} | ${f(r.heldSpeed, 1)} / ${f(r.firingSpeed, 2)} | ${cur === t.tier ? `${t.tier} =` : `${cur} → ${t.tier}`} |`,
            );
        }
    }
    out.push("");
    out.push("## Other stats");
    out.push("");
    out.push(
        "| gun | class | hs x | obstacle x | burst / pump | switch | deploy group | range | falloff | ammo (spawn) | speed equip / attack / carry | special |",
    );
    out.push("|---|---|---|---|---|---|---|---|---|---|---|---|");
    for (const cls of CLASS_ORDER) {
        for (const id of sortRows(M.rows.filter((r: Any) => r.cls === cls).map((r: Any) => r.id))) {
            const r = row.get(id);
            out.push(
                `| \`${id}\`${r.dualOf ? ` (dual ${r.dualOf})` : ""} | ${r.gclass} | ${r.headshotMult} | ${r.obstacleDamage} | ${r.burst || "-"} | ${r.switchDelay} | ${r.deployGroup ?? "-"} | ${f0(r.range)} | ${r.falloff} | ${r.ammo} (${r.ammoSpawn}) | ${r.speedEquip} / ${r.speedAttack} / ${r.speedCarry} | ${r.special.join("; ") || "-"} |`,
            );
        }
    }
    out.push("");
    return out.join("\n");
}

function csv(): string {
    const cols = [
        "id",
        "name",
        "gclass",
        "cls",
        "dualOf",
        "ammo",
        "ammoFactor",
        "ammoSpawn",
        "fireMode",
        "damage",
        "pellets",
        "explosion",
        "shrapnel",
        "headshotMult",
        "obstacleDamage",
        "fireDelay",
        "burst",
        "rpm",
        "mag",
        "magExt",
        "reloadTime",
        "reloadType",
        "fullReload",
        "switchDelay",
        "deployGroup",
        "shotSpread",
        "moveSpread",
        "fsa",
        "bulletSpeed",
        "range",
        "falloff",
        "speedEquip",
        "speedAttack",
        "speedCarry",
        "heldSpeed",
        "firingSpeed",
        "mobilityCost",
        "burstDps",
        "sustainedDps",
        "magDamage",
        "killsPerMag",
        "aimK",
        "F",
        "Fdel",
    ];
    const lines = [
        [
            ...cols,
            "band",
            "perfA0",
            "perfA1",
            "perfA2",
            "expA0",
            "expA1",
            "expA2",
            "avgA0",
            "avgA1",
            "avgA2",
            "begA0",
            "begA1",
            "begA2",
            "composite",
            "compositeExpert",
            "statTier",
            "tier",
            "currentTier",
            "currentF",
            "mainMap",
        ].join(","),
    ];
    const q = (v: unknown) => {
        const s =
            v === undefined || v === null
                ? ""
                : typeof v === "number"
                  ? Number.isFinite(v)
                      ? String(Math.round(v * 1000) / 1000)
                      : "inf"
                  : String(v);
        return /[",]/.test(s) ? `"${s.replaceAll('"', '""')}"` : s;
    };
    for (const r of M.rows) {
        const t = tier.get(r.id);
        const b = r.bandTtk;
        lines.push(
            [
                ...cols.map((c) => q(r[c])),
                q(`${r.band[0]}-${r.band[r.band.length - 1]}`),
                q(r.perfect.a0),
                q(r.perfect.a1),
                q(r.perfect.a2),
                q(b.expert.a0),
                q(b.expert.a1),
                q(b.expert.a2),
                q(b.average.a0),
                q(b.average.a1),
                q(b.average.a2),
                q(b.beginner.a0),
                q(b.beginner.a1),
                q(b.beginner.a2),
                q(t.C),
                q(t.CE),
                q(t.stat),
                q(t.tier),
                q(t.current),
                q(t.currentF),
                q(t.mainMap),
            ].join(","),
        );
    }
    return `${lines.join("\n")}\n`;
}

