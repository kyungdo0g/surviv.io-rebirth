function tierList(inRows: boolean): string {
    const lines: string[] = [];
    for (const t of ORDER) {
        const ids = T.rows.filter((r: Any) => r.inRows === inRows && r.tier === t).sort((a: Any, b: Any) => b.C - a.C);
        if (!ids.length) continue;
        lines.push(
            `| **${t}** | ${ids.map((r: Any) => `${disp(r.id)}${r.current && r.current !== r.tier ? ` <sub>${r.current}</sub>` : ""}${r.tier !== r.stat ? "\\*" : ""}`).join(", ")} |`,
        );
    }
    return [
        "| tier | guns (best composite first; <sub>old tier</sub> when it moved; \\* = ruling or consistency, not the stat tier) |",
        "|---|---|",
        ...lines,
    ].join("\n");
}

const MS: Any = JSON.parse(readFileSync(`${DIR}/metrics-still.json`, "utf8"), inf);
const TS: Any = JSON.parse(readFileSync(`${DIR}/tiers-still.json`, "utf8"), inf);
function launcherTable(): string {
    const lines = [
        "| gun | strafing target: stat tier (composite) | TTK avg A1 | stationary target: stat tier (composite) | TTK avg A1 | current | proposed |",
        "|---|---|---|---|---|---|---|",
    ];
    const ids = ["mgl", "gl06", "m202", "rpg7", "panzerfaust", "m79", "potato_cannon", "usas"];
    for (const id of ids) {
        const t = tier.get(id);
        const ts = TS.rows.find((x: Any) => x.id === id);
        const r = row.get(id);
        const rs = MS.rows.find((x: Any) => x.id === id);
        const pk = (m: Any) =>
            m.pKillCharges !== undefined ? ` (kill per pickup ${Math.round(m.pKillCharges * 100)} %)` : "";
        lines.push(
            `| ${name(id)} | ${t.stat} (${f(t.C)}) | ${f(r.bandTtk.average.a1)}${pk(r)} | ${ts.stat} (${f(ts.C)}) | ${f(rs.bandTtk.average.a1)}${pk(rs)} | ${t.current} | ${t.tier} |`,
        );
    }
    return lines.join("\n");
}

const W = T.W;
const PART_LABEL: Record<string, string> = {
    role: "role",
    range: "range",
    alpha: "damage/shot",
    sustain: "sustain",
    handling: "handling",
    ammo: "ammo",
};
function autoReason(id: string): string {
    const r = row.get(id);
    const p = T.score[id].parts;
    const items = Object.keys(W)
        .map((k) => [k, W[k] * p[k]] as [string, number])
        .sort((a, b) => Math.abs(b[1]) - Math.abs(a[1]));
    const fact = (k: string) => {
        const b = `${r.band[0]}-${r.band[r.band.length - 1]} u`;
        if (k === "role") return `TTK ${f(r.bandTtk.average.a1)} s (avg aim, level 1) at ${b}`;
        if (k === "range")
            return r.range < 60
                ? `range ${f0(r.range)} u`
                : `kill rate across 5-80 u x${f(2 ** p.range, 2)} the median`;
        if (k === "alpha") return `${dmgStr(r)} per shot`;
        if (k === "sustain")
            return `${r.mag}-round ${r.reloadType === "none" ? "pickup" : "magazine"}, ${f(r.killsPerMag, 1)} kills each`;
        if (k === "handling")
            return `${f(r.heldSpeed, 1)} / ${f(r.firingSpeed, 2)} u/s held / firing${r.switchDelay > 0.75 ? `, switch ${r.switchDelay} s` : ""}`;
        return `${r.ammo} has no box row`;
    };
    return items
        .slice(0, 2)
        .map(([k, v]) => `${PART_LABEL[k]} ${v >= 0 ? "+" : ""}${f(v)} (${fact(k)})`)
        .join("; ");
}

function changes(): string {
    const lines = ["| gun | old | new | steps | composite | reason |", "|---|---|---|---|---|---|"];
    const moved = T.rows.filter((r: Any) => r.inRows && r.current !== r.tier);
    moved.sort(
        (a: Any, b: Any) =>
            Math.abs(rk(b.tier) - rk(b.current)) - Math.abs(rk(a.tier) - rk(a.current)) || rk(a.tier) - rk(b.tier),
    );
    for (const r of moved) {
        const steps = rk(r.current) - rk(r.tier);
        const why = REASON[r.id] ?? autoReason(r.id);
        const flag = r.flags
            .filter((x: string) => !x.startsWith("ruling agrees"))
            .map((x: string) => x.split(":")[0])
            .join(", ");
        lines.push(
            `| ${name(r.id)}${r.mainMap ? "" : " (off-map)"} | ${r.current} | ${r.tier} | ${steps > 0 ? `+${steps}` : steps} | ${f(r.C)} | ${why}${flag ? ` *(${flag})*` : ""} |`,
        );
    }
    return lines.join("\n");
}

function conflicts(): string {
    const lines = ["| gun | ruling / pin | stat tier | composite | what the numbers say |", "|---|---|---|---|---|"];
    for (const r of T.rows.filter((x: Any) => x.flags.some((fl: string) => !fl.startsWith("ruling agrees")))) {
        for (const fl of r.flags) {
            if (fl.startsWith("ruling agrees")) continue;
            lines.push(`| ${name(r.id)} | ${r.tier} | ${r.stat} | ${f(r.C)} | ${REASON[`conflict:${r.id}`] ?? fl} |`);
        }
    }
    return lines.join("\n");
}

function proposedRows(): string {
    const src = readFileSync(GUN_TIERS, "utf8");
    const start = src.indexOf("const ROWS: readonly Row[] = [");
    const end = src.indexOf("];", start);
    const body = src.slice(start, end).split("\n").slice(1);
    const out: string[] = [
        "// biome-ignore format: a few guns per line keep the table readable",
        "const ROWS: readonly Row[] = [",
    ];
    let block = 0;
    let inComment = false;
    for (const line of body) {
        const trimmed = line.trim();
        if (!trimmed) continue;
        if (trimmed.startsWith("//")) {
            const mine = inComment ? ROW_COMMENTS[block - 1] : ROW_COMMENTS[block];
            if (!inComment) {
                for (const c of mine ?? []) out.push(`    // ${c}`);
                block++;
            }
            // a null entry keeps the block's own lines (the round 6 loot notes behind the mainMap flags)
            if (mine === null) out.push(`    ${trimmed}`);
            inComment = true;
            continue;
        }
        inComment = false;
        const ids = [...trimmed.matchAll(/\["([a-z0-9_]+)",/g)].map((m) => m[1]);
        const trail = trimmed.includes("//") ? trimmed.slice(trimmed.indexOf("//") + 2).trim() : "";
        const keep = trail.replace(/^(dual )?est\.;?\s*/, "").trim();
        const cells = ids.map((id) => {
            const t = tier.get(id);
            return `["${id}", "${t.tier}", ${Math.round(t.F * 100) / 100}, ${t.mainMap}]`;
        });
        out.push(`    ${cells.join(", ")},${keep ? ` // ${keep}` : ""}`);
    }
    out.push("];");
    return out.join("\n");
}

function thresholds(): string {
    const th = T.thresholds;
    const cuts = Object.entries(th).map(([t, v]) => `${t} ≥ ${f(v as number, 3)}`);
    return `${cuts.join(", ")}, D below (S-aim: an aim gun, F ≤ ${T.F_AIM}, whose blended or expert-only composite reaches the S cut).`;
}

const tpl = readFileSync(`${HERE}gun-tiers.template.md`, "utf8");
const sens = readFileSync(`${DIR}/sens.txt`, "utf8")
    .trim()
    .split("\n")
    .map((l) => `- ${l.replace(/([a-z0-9_]+) ([A-DS][a-z+-]*)->([A-DS][a-z+-]*)/g, "`$1` $2 → $3")}`)
    .join("\n");
const doc = tpl
    .replace("{{THRESHOLDS}}", thresholds())
    .replace("{{TIERLIST}}", tierList(true))
    .replace("{{LAUNCHERS}}", launcherTable())
    .replace("{{CHANGES}}", changes())
    .replace("{{CONFLICTS}}", conflicts())
    .replace("{{ROWS}}", proposedRows())
    .replace("{{SENS}}", sens)
    .replace("{{AMMO}}", ammoTable())
    .replace(
        "{{WEIGHTS}}",
        Object.entries(W)
            .map(([k, v]) => `${PART_LABEL[k]} ${v}`)
            .join(", "),
    );
const rows = proposedRows();
writeFileSync(resolve("docs/design/gun-tiers.md"), doc);
writeFileSync(resolve("docs/design/gun-tiers-stats.md"), statTables());
writeFileSync(resolve("docs/design/gun-tiers-stats.csv"), csv());
writeFileSync(`${DIR}/rows.ts.txt`, `${rows}\n`);
if (process.argv.includes("--apply")) {
    const src = readFileSync(GUN_TIERS, "utf8");
    const start = src.indexOf("// biome-ignore format: a few guns per line keep the table readable\nconst ROWS");
    const end = src.indexOf("];", start) + 2;
    writeFileSync(GUN_TIERS, src.slice(0, start) + rows + src.slice(end));
}
console.log(
    "wrote docs/design/gun-tiers.md, gun-tiers-stats.md, gun-tiers-stats.csv; doc lines:",
    doc.split("\n").length,
);
