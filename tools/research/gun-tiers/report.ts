// Gun tier rebuild, step 4: writes docs/design/gun-tiers.md (from gun-tiers.template.md, reasons.ts and the generated
// tables), docs/design/gun-tiers-stats.md and .csv, and the ROWS for gunTiers.ts (research-cache/gun-tiers/rows.ts.txt).
// usage (repo root, after compute, score and sens): node tools/research/gun-tiers/report.ts [--apply: write the ROWS]
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { ammoTable } from "./ammo.ts";
import { REASON, ROW_COMMENTS } from "./reasons.ts";

type Any = any;
const HERE = new URL(".", import.meta.url).pathname;
const DIR = resolve("research-cache/gun-tiers");
/** the bots' tier table: its ROWS layout and comments frame the generated ROWS (--apply writes them back) */
const GUN_TIERS = resolve("packages/bots/src/knowledge/gunTiers.ts");
const inf = (_: string, v: unknown) => (v === "Infinity" ? Number.POSITIVE_INFINITY : v);
const M: Any = JSON.parse(readFileSync(`${DIR}/metrics.json`, "utf8"), inf);
const T: Any = JSON.parse(readFileSync(`${DIR}/tiers.json`, "utf8"), inf);
const row = new Map<string, Any>(M.rows.map((r: Any) => [r.id, r]));
const tier = new Map<string, Any>(T.rows.map((r: Any) => [r.id, r]));
const ORDER = ["S", "S-aim", "A+", "A", "A-", "B+", "B", "B-", "C+", "C", "D"];
const CLASS_ORDER = ["lmg", "sniper", "dmr", "rifle", "shotgun", "smg", "pistol", "launcher"];
const rk = (t: string) => ORDER.indexOf(t);

const f = (x: number, d = 2) => (Number.isFinite(x) ? x.toFixed(d) : "∞");
const f0 = (x: number) => (Number.isFinite(x) ? Math.round(x).toString() : "∞");
/** display name: the def name, made unique for the winter skins and the .45 Vector */
const DISPLAY: Record<string, string> = {
    awc_winter: "AWM-S (winter)",
    svd_winter: "SVD-63 (winter)",
    sv98_winter: "SV-98 (winter)",
    vector45: "Vector .45",
};
const disp = (id: string) => DISPLAY[id] ?? row.get(id).name;
const name = (id: string) => `${disp(id)} (\`${id}\`)`;
const dmgStr = (r: Any) => {
    let s = r.pellets > 1 ? `${r.damage}x${r.pellets}` : `${r.damage}`;
    if (r.explosion) s += `+${r.explosion}e${r.shrapnel ? `+${r.shrapnel}s` : ""}`;
    return s;
};
const reloadStr = (r: Any) =>
    r.reloadType === "none"
        ? "none"
        : r.reloadType === "full"
          ? `${r.reloadTime}`
          : `${r.reloadTime}/${r.reloadType.replace("per ", "")} (${f(r.fullReload, 1)})`;
const ttk3 = (t: Any) => `${f(t.a0)} / ${f(t.a1)} / ${f(t.a2)}`;
const sortRows = (ids: string[]) =>
    ids.sort((a, b) => rk(tier.get(a).tier) - rk(tier.get(b).tier) || tier.get(b).C - tier.get(a).C);

